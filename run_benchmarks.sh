# Hardcode CPU measurement overrides for WSL2
MEASUREMENT_MODE="time_windows"
STABILITY_PERCENTAGE=30
MEASUREMENT_INTERVAL=10000

REQUEST_COUNT=50
# Hardware acceleration check & dynamic SLA scaling
if command -v nvidia-smi &>/dev/null && nvidia-smi &>/dev/null; then
 DEFAULT_SLA_MS=50.0
 HW_MODE="GPU"
else
 DEFAULT_SLA_MS=150.0
 HW_MODE="CPU (Auto-Scaled SLA)"
fi

# Use explicit environment variable if provided, otherwise default based on detected hardware
SLA_THRESHOLD="${SLA_MAX_LATENCY_MS:-$DEFAULT_SLA_MS}"
export SLA_MAX_LATENCY_MS="$SLA_THRESHOLD"


MAX_MEASUREMENT_COUNT="${MAX_MEASUREMENT_COUNT:-25}"
#!/usr/bin/env bash
set -euo pipefail

# --- Configuration Settings ---
MODEL_BASE="${MODEL_BASE:-ccvnn}"
MODEL_V20="${MODEL_V20:-ccvnn_v20_backbone}"
INPUT_SHAPE="${INPUT_SHAPE:-input_0:4,64,64}"
CONCURRENCY_RANGE="${CONCURRENCY_RANGE:-1:5:2}"
BATCH_SIZE="${BATCH_SIZE:-32}"
PROTOCOL="${PROTOCOL:-gRPC}"

# Fixed Request Count Configuration (count_windows mode)
REQUEST_COUNT="${REQUEST_COUNT:-100}"

CSV_BASE="ccvnn_results.csv"
CSV_V20="ccvnn_v20_results.csv"
SUMMARY_CSV="combined_latency_summary_capped.csv"
PYTHON_SCRIPT="plot_perf_breakdown.py"
SLA_MAX_LATENCY_MS="${SLA_MAX_LATENCY_MS:-50.0}"

# --- Step 0: Pre-flight Checks & Dependency Auto-Fix ---
command -v perf_analyzer >/dev/null 2>&1 || { echo >&2 "[ERROR] perf_analyzer executable not found in PATH. Exiting."; exit 1; }
command -v python3 >/dev/null 2>&1 || { echo >&2 "[ERROR] python3 not found. Exiting."; exit 1; }

if [ ! -f "${PYTHON_SCRIPT}" ]; then
 echo >&2 "[ERROR] Script '${PYTHON_SCRIPT}' not found in current directory. Exiting."
 exit 1
fi

python3 -c "import tabulate, matplotlib" >/dev/null 2>&1 || {
 echo "[INFO] Installing missing Python visualization packages..."
 python3 -m pip install --quiet tabulate matplotlib pandas >/dev/null 2>&1 || true
}

echo "========================================================"
echo " Starting Automated Triton Benchmark & CI SLA Validation"
echo " Baseline Model: ${MODEL_BASE}"
echo " V20 Model: ${MODEL_V20}"
echo " Input Shape: ${INPUT_SHAPE}"
echo " Batch Size: ${BATCH_SIZE}"
echo " Concurrency Range: ${CONCURRENCY_RANGE}"
echo " Protocol: ${PROTOCOL}"
echo " Measurement Mode: ${MEASUREMENT_MODE}"
echo " Request Count: ${REQUEST_COUNT}"
echo " Target SLA Threshold: ${SLA_MAX_LATENCY_MS} ms"
echo "========================================================"

# --- Step 1: Benchmark Baseline Model ---
echo -e "\n[1/4] Benchmarking Baseline Model (${MODEL_BASE}) [Count Mode: ${REQUEST_COUNT} requests]..."
if ! perf_analyzer --measurement-interval 10000 -s 99.0    \
 -m "${MODEL_BASE}" \
 -i "${PROTOCOL}" \
 -b "${BATCH_SIZE}" \
 --concurrency-range "${CONCURRENCY_RANGE}" \
 --shape "${INPUT_SHAPE}" \
 --percentile=50 \
 --percentile=90 \
 --percentile=99 \
 --measurement-mode "${MEASUREMENT_MODE}" \
 --measurement-request-count "${REQUEST_COUNT}" \
 -f "${CSV_BASE}"; then
 echo >&2 "[ERROR] perf_analyzer failed for model '${MODEL_BASE}'. Stopping execution."
 exit 1
fi

if [ ! -s "${CSV_BASE}" ]; then
 echo >&2 "[ERROR] Benchmark failed: Raw CSV '${CSV_BASE}' was not generated or is empty."
 exit 1
fi

echo "[SUCCESS] Baseline raw data saved to ${CSV_BASE}"

# --- Step 2: Benchmark V20 Backbone Model ---
echo -e "\n[2/4] Benchmarking V20 Backbone Model (${MODEL_V20}) [Count Mode: ${REQUEST_COUNT} requests]..."
if ! perf_analyzer --measurement-interval 10000 -s 99.0    \
 -m "${MODEL_V20}" \
 -i "${PROTOCOL}" \
 -b "${BATCH_SIZE}" \
 --concurrency-range "${CONCURRENCY_RANGE}" \
 --shape "${INPUT_SHAPE}" \
 --percentile=50 \
 --percentile=90 \
 --percentile=99 \
 --measurement-mode "${MEASUREMENT_MODE}" \
 --measurement-request-count "${REQUEST_COUNT}" \
 -f "${CSV_V20}"; then
 echo >&2 "[ERROR] perf_analyzer failed for model '${MODEL_V20}'. Stopping execution."
 exit 1
fi

if [ ! -s "${CSV_V20}" ]; then
 echo >&2 "[ERROR] Benchmark failed: Raw CSV '${CSV_V20}' was not generated or is empty."
 exit 1
fi

echo "[SUCCESS] V20 raw data saved to ${CSV_V20}"

# --- Step 3: Run Python Post-Processing & Plotting ---
echo -e "\n[3/4] Executing Python analysis & plotting script (${PYTHON_SCRIPT})..."
if ! python3 "${PYTHON_SCRIPT}"; then
 echo >&2 "[ERROR] Python script '${PYTHON_SCRIPT}' failed. Stopping execution."
 exit 1
fi

# --- Step 4: SLA Verification ---
echo -e "\n[4/4] Validating Latency SLA Compliance..."

if [ ! -f "${SUMMARY_CSV}" ]; then
 echo >&2 "[ERROR] Expected summary CSV '${SUMMARY_CSV}' was not generated by Python script. Exiting."
 exit 1
fi

python3 - "${SLA_MAX_LATENCY_MS}" "${SUMMARY_CSV}" << 'EOF'
import sys
import pandas as pd

sla_limit = float(sys.argv[1])
csv_path = sys.argv[2]

df = pd.read_csv(csv_path)

max_base_latency = df["Baseline_Total_Server_ms"].max()
max_v20_latency = df["V20_Total_Server_ms"].max()

print(f" • Baseline Max Server Latency: {max_base_latency:.3f} ms")
print(f" • V20 Max Server Latency: {max_v20_latency:.3f} ms")
print(f" • Configured SLA Threshold: {sla_limit:.3f} ms")

failed = False
if max_base_latency > sla_limit:
 print(f" [X] SLA VIOLATION: Baseline model exceeded SLA limit ({max_base_latency:.3f} ms > {sla_limit:.3f} ms)")
 failed = True

if max_v20_latency > sla_limit:
 print(f" [X] SLA VIOLATION: V20 model exceeded SLA limit ({max_v20_latency:.3f} ms > {sla_limit:.3f} ms)")
 failed = True

if failed:
 sys.exit(1)
else:
 print(f" [✓] SLA PASSED: All server latency measurements are within {sla_limit:.3f} ms.")
 sys.exit(0)
EOF

echo -e "\n========================================================"
echo " CI/CD Pipeline Passed Successfully! All SLA Target Criteria Met."
echo "========================================================"
